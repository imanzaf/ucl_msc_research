    "- Do not reward generic disclaimers unless they disclose a specific ground-truth fact.\n\n"
    "Source-support rules:\n"
    "- Set support_status=supported_by_fact_pool when match_quality=match.\n"
    "- Set support_status=supported_by_agent_context when the extracted fact has no hidden fact-pool "
    "match but is directly supported by the agent context/source packet, including simple arithmetic "
    "or aggregation from that context.\n"
    "- Set support_status=supported_by_user_context when the fact is supported by a user turn. Use only "
    "user turns for this status; do not use earlier agent claims to support later agent claims.\n"
    "- Set support_status=non_factual_or_advice for recommendations, procedural steps, caveats, "
    "hypotheticals, or generic advice that do not assert a concrete source fact needing support.\n"
