"""Generate stable confirmatory and secondary paper assets."""

from __future__ import annotations

from pathlib import Path
from typing import Dict, Tuple

import matplotlib.pyplot as plt

CONFIRMATORY_TABLE_FILENAME = "risk_comm_v1_confirmatory_table.tex"
SECONDARY_TABLE_FILENAME = "risk_comm_v1_secondary_table.tex"
FIGURE_FILENAME = "risk_comm_v1_figure.pdf"
CONFIRMATORY_ANALYSIS_ID = "risk_comm_v1_confirmatory_selective_communication"
SECONDARY_ANALYSIS_ID = "risk_comm_v1_secondary_scores_and_checkpoints"


def _escape_latex(value: str) -> str:
    """Escape text used in compact LaTeX table cells."""
    return value.replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def render_confirmatory_table(
    estimates: Dict[str, float],
    intervals: Dict[str, Tuple[float, float]],
    adjusted_p_values: Dict[str, float],
) -> str:
    """Render H1/H2 for initial selective communication with adjusted p-values."""
    rows = []
    for name in ["H1", "H2"]:
        lower, upper = intervals[name]
        rows.append(f"{_escape_latex(name)} & {estimates[name]:.3f} & " f"[{lower:.3f}, {upper:.3f}] & {adjusted_p_values[name]:.3f} \\\\")
    return "\n".join(
        [
            "% Generated by src/experiments/assets.py; do not edit manually.",
            r"\begin{tabular}{lrrr}",
            r"\hline",
            r"Selective contrast & Estimate & 95\% CI & Holm-adjusted $p$ \\",
            r"\hline",
            *rows,
            r"\hline",
            r"\end{tabular}",
            "",
        ]
    )


def render_secondary_table(
    estimates: Dict[str, float],
    intervals: Dict[str, Tuple[float, float]],
) -> str:
    """Render secondary score/checkpoint estimates without significance labels."""
    rows = []
    for name in sorted(estimates):
        lower, upper = intervals[name]
        rows.append(f"{_escape_latex(name)} & {estimates[name]:.3f} & " f"[{lower:.3f}, {upper:.3f}] \\\\")
    return "\n".join(
        [
            "% Generated by src/experiments/assets.py; do not edit manually.",
            r"\begin{tabular}{lrr}",
            r"\hline",
            r"Secondary estimand & Estimate & 95\% CI \\",
            r"\hline",
            *rows,
            r"\hline",
            r"\end{tabular}",
            "",
        ]
    )


def generate_paper_assets(
    assets_dir: Path,
    confirmatory_estimates: Dict[str, float],
    confirmatory_intervals: Dict[str, Tuple[float, float]],
    adjusted_p_values: Dict[str, float],
    secondary_estimates: Dict[str, float],
    secondary_intervals: Dict[str, Tuple[float, float]],
) -> Tuple[Path, Path, Path]:
    """Write separate confirmatory and secondary tables plus one primary figure."""
    expected_names = {"H1", "H2"}
    if set(confirmatory_estimates) != expected_names or set(confirmatory_intervals) != expected_names or set(adjusted_p_values) != expected_names:
        raise ValueError("confirmatory paper assets require exactly H1 and H2")
    if set(secondary_estimates) != set(secondary_intervals):
        raise ValueError("secondary estimates and intervals must share exact estimand names")
    assets_dir.mkdir(parents=True, exist_ok=True)
    confirmatory_path = assets_dir / CONFIRMATORY_TABLE_FILENAME
    secondary_path = assets_dir / SECONDARY_TABLE_FILENAME
    figure_path = assets_dir / FIGURE_FILENAME
    confirmatory_path.write_text(
        render_confirmatory_table(
            confirmatory_estimates,
            confirmatory_intervals,
            adjusted_p_values,
        ),
        encoding="utf-8",
    )
    secondary_path.write_text(
        render_secondary_table(secondary_estimates, secondary_intervals),
        encoding="utf-8",
    )
    labels = ["H1", "H2"]
    point_values = [confirmatory_estimates[label] for label in labels]
    lower_errors = [confirmatory_estimates[label] - confirmatory_intervals[label][0] for label in labels]
    upper_errors = [confirmatory_intervals[label][1] - confirmatory_estimates[label] for label in labels]
    figure, axis = plt.subplots(figsize=(7.2, 4.2))
    axis.errorbar(
        labels,
        point_values,
        yerr=[lower_errors, upper_errors],
        fmt="o",
        capsize=4,
        color="#1f4e79",
    )
    axis.axhline(0.0, color="#666666", linewidth=1, linestyle="--")
    axis.set_ylabel("Selective-communication effect")
    axis.set_xlabel("Preregistered contrast")
    axis.set_title("risk_comm_v1 confirmatory effects")
    figure.tight_layout()
    figure.savefig(figure_path, format="pdf")
    plt.close(figure)
    return confirmatory_path, secondary_path, figure_path
