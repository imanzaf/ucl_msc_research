"""Generate stable risk_comm_v1 LaTeX and PDF paper assets from analysis summaries."""

from __future__ import annotations

from pathlib import Path
from typing import Dict, Tuple

import matplotlib.pyplot as plt

TABLE_FILENAME = "risk_comm_v1_table.tex"
FIGURE_FILENAME = "risk_comm_v1_figure.pdf"


def _escape_latex(value: str) -> str:
    """Escape text used in compact LaTeX table cells."""
    return value.replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def render_confirmatory_table(
    estimates: Dict[str, float],
    intervals: Dict[str, Tuple[float, float]],
    adjusted_p_values: Dict[str, float],
) -> str:
    """Render the two preregistered composite-score estimands."""
    rows = []
    for name in ["H1", "H2"]:
        lower, upper = intervals[name]
        rows.append(f"{_escape_latex(name)} & {estimates[name]:.3f} & [{lower:.3f}, {upper:.3f}] & {adjusted_p_values[name]:.3f} \\\\")
    body = "\n".join(rows)
    return (
        "% Generated by src/experiments/assets.py; do not edit manually.\n"
        "\\begin{tabular}{lrrr}\n"
        "\\hline\n"
        "Contrast & Estimate & 95\\% CI & Holm-adjusted $p$ \\\\\n"
        "\\hline\n"
        f"{body}\n"
        "\\hline\n"
        "\\end{tabular}\n"
    )


def generate_paper_assets(
    assets_dir: Path,
    estimates: Dict[str, float],
    intervals: Dict[str, Tuple[float, float]],
    adjusted_p_values: Dict[str, float],
) -> Tuple[Path, Path]:
    """Write stable LaTeX table and PDF figure filenames for risk_comm_v1."""
    expected_names = {"H1", "H2"}
    if set(estimates) != expected_names or set(intervals) != expected_names or set(adjusted_p_values) != expected_names:
        raise ValueError("paper assets require exactly H1 and H2")
    assets_dir.mkdir(parents=True, exist_ok=True)
    table_path = assets_dir / TABLE_FILENAME
    figure_path = assets_dir / FIGURE_FILENAME
    table_path.write_text(render_confirmatory_table(estimates, intervals, adjusted_p_values), encoding="utf-8")
    labels = ["H1", "H2"]
    point_values = [estimates[label] for label in labels]
    lower_errors = [estimates[label] - intervals[label][0] for label in labels]
    upper_errors = [intervals[label][1] - estimates[label] for label in labels]
    figure, axis = plt.subplots(figsize=(7.2, 4.2))
    axis.errorbar(labels, point_values, yerr=[lower_errors, upper_errors], fmt="o", capsize=4, color="#1f4e79")
    axis.axhline(0.0, color="#666666", linewidth=1, linestyle="--")
    axis.set_ylabel("Paired effect estimate")
    axis.set_xlabel("Preregistered contrast")
    axis.set_title("risk_comm_v1 confirmatory effects")
    figure.tight_layout()
    figure.savefig(figure_path, format="pdf")
    plt.close(figure)
    return table_path, figure_path
