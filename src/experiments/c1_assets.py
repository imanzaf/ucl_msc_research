"""Generate stable reporting assets for the single-model C1 diagnostic."""

from __future__ import annotations

from decimal import Decimal
from pathlib import Path
from typing import Dict, List

from src.data_models.experiments import ConversationTranscript, RunOutcomeStatus
from src.data_models.scoring import EvaluationCheckpoint, ScoredConversationBundle

C1_TABLE_FILENAME = "c1_llama_2x2_v1_table.tex"


def _latex_escape(value: str) -> str:
    """Escape underscores in short generated LaTeX labels."""
    return value.replace("_", r"\_")


def generate_c1_paper_assets(
    transcripts: List[ConversationTranscript],
    bundles: List[ScoredConversationBundle],
    assets_dir: Path,
) -> Path:
    """Write a stable completion-and-score table for the four C1 cells."""
    transcript_by_id = {transcript.run_unit.run_unit_id: transcript for transcript in transcripts}
    initial_scores: Dict[str, List[Decimal]] = {}
    for bundle in bundles:
        transcript = transcript_by_id.get(bundle.run_unit_id)
        if transcript is None:
            raise ValueError("C1 asset bundle has no matching transcript")
        metric = next(item for item in bundle.metrics if item.checkpoint == EvaluationCheckpoint.INITIAL)
        initial_scores.setdefault(transcript.run_unit.cell.cell_id, []).append(metric.selective_risk_communication_score)
    rows: List[str] = []
    for cell_id in sorted({transcript.run_unit.cell.cell_id for transcript in transcripts}):
        cell_transcripts = [transcript for transcript in transcripts if transcript.run_unit.cell.cell_id == cell_id]
        completed = sum(transcript.outcome_status == RunOutcomeStatus.COMPLETED for transcript in cell_transcripts)
        scores = initial_scores.get(cell_id, [])
        mean_score = f"{sum(scores, Decimal('0')) / Decimal(len(scores)):.4f}" if scores else "--"
        rows.append(f"{_latex_escape(cell_id)} & {completed} & {len(cell_transcripts)} & {mean_score} \\\\")
    assets_dir.mkdir(parents=True, exist_ok=True)
    output = assets_dir / C1_TABLE_FILENAME
    output.write_text(
        "\n".join(
            [
                "% Generated by risk-comm; do not edit manually.",
                r"\begin{tabular}{lrrr}",
                r"\toprule",
                r"Cell & Completed & Planned & Mean initial score \\",
                r"\midrule",
                *rows,
                r"\bottomrule",
                r"\end{tabular}",
                "",
            ]
        ),
        encoding="utf-8",
    )
    return output
